CREATE TABLE IF NOT EXISTS orders (
  id SERIAL PRIMARY KEY,
  "buyerId" INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  "listingId" INTEGER REFERENCES listings(id) ON DELETE SET NULL ON UPDATE CASCADE,
  title VARCHAR(150) NOT NULL,
  amount INTEGER NOT NULL CHECK (amount BETWEEN 50 AND 99999999),
  currency VARCHAR(3) NOT NULL DEFAULT 'usd' CHECK (currency = 'usd'),
  status VARCHAR(20) NOT NULL DEFAULT 'paid_test' CHECK (status = 'paid_test'),
  "stripeSessionId" VARCHAR(255) NOT NULL UNIQUE,
  "createdAt" TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS orders_buyer_id ON orders ("buyerId");
